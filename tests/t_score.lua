    T.test("score: a missing item and one that never loads are told apart", function()
        local W = arms()
        local ghost = "item:99999"
        local r, why = W.EG.Score.Compare(ghost)
        T.eq(r, nil) T.eq(why, "loading")
        local state, retry = W.EG.Score.UpgradeState(ghost)
        T.eq(state, nil) T.eq(retry, true)
        W.fire("GET_ITEM_INFO_RECEIVED", 99999, false)
        r, why = W.EG.Score.Compare(ghost)
        T.eq(r, nil) T.eq(why, "invalid")
        state, retry = W.EG.Score.UpgradeState(ghost)
        T.eq(state, nil) T.eq(retry, false, "no point asking again")
    end)

    T.test("score: UpgradeState reports pending data", function()
        local W = arms()
